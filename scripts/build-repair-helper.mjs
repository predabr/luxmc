import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

if (process.platform !== "win32") process.exit(0);
const prepare = process.argv.includes("--prepare");
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const targetDirectory = process.env.CARGO_TARGET_DIR || join(root, "src-tauri", "target");
const cargo = process.platform === "win32" ? join(process.env.USERPROFILE, ".cargo", "bin", "cargo.exe") : "cargo";
const rustc = process.platform === "win32" ? join(process.env.USERPROFILE, ".cargo", "bin", "rustc.exe") : "rustc";
const info = spawnSync(rustc, ["-vV"], {encoding:"utf8",windowsHide:true});
if (info.status !== 0) throw Error("NÃ£o foi possÃ­vel determinar o alvo Rust.");
const target = process.env.TAURI_ENV_TARGET_TRIPLE || /^host: (.+)$/m.exec(info.stdout)?.[1];
if (!target) throw Error("Alvo do verificador indisponÃ­vel.");
const extension = target.includes("windows") ? ".exe" : "";
const binaryCandidates = [join(targetDirectory,"release",`luxmc${extension}`),join(targetDirectory,target,"release",`luxmc${extension}`)].filter(existsSync).sort((a,b)=>statSync(b).mtimeMs-statSync(a).mtimeMs);
if (!prepare && !binaryCandidates.length) throw Error("Compile o Luxmc antes de empacotar o verificador.");
const main = prepare ? Buffer.from("unbundled verification placeholder") : readFileSync(binaryCandidates[0]);
const marker = Buffer.from("PE_VAR_NSS");
for(let offset=main.indexOf(marker);offset>=0;offset=main.indexOf(marker,offset+marker.length)) Buffer.from("PE_VAR_UNK").copy(main,offset);
const expected = createHash("sha256").update(main).digest("hex");
const result = spawnSync(cargo,["build","--release","--target",target,"--manifest-path",join(root,"src-tauri","repair-helper","Cargo.toml")],{stdio:"inherit",windowsHide:true,env:{...process.env,CARGO_TARGET_DIR:targetDirectory,LUXMC_MAIN_SHA256:expected}});
if(result.status !== 0) throw Error("Falha na compilaÃ§Ã£o do verificador.");
const helper = join(targetDirectory,target,"release",`luxmc-repair${extension}`);
const externalDirectory = join(root,"src-tauri","binaries");
mkdirSync(externalDirectory,{recursive:true});
copyFileSync(helper,join(externalDirectory,`luxmc-repair-${target}${extension}`));
if (!prepare) copyFileSync(helper,join(dirname(binaryCandidates[0]),`luxmc-repair${extension}`));
console.log(`Verificador preparado para Luxmc ${JSON.parse(readFileSync(join(root,"package.json"),"utf8")).version} (${expected.slice(0,12)}).`);
