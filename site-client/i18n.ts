    const browserLanguage = (navigator.languages?.[0] || navigator.language || "en").toLowerCase();
    let language = browserLanguage.startsWith("pt") ? "pt" : browserLanguage.startsWith("es") ? "es" : "en";
    try {
        const saved = localStorage.getItem("luxmc_lang");
        if (saved && ["pt", "en", "es"].includes(saved))
            language = saved;
    }
    catch { }
    function applyLanguage(next: any) {
        if (!["pt", "en", "es"].includes(next))
            return;
        language = next;
        try {
            localStorage.setItem("luxmc_lang", next);
        }
        catch { }
        document.documentElement.lang = next === "pt" ? "pt-BR" : next;
        for (const node of document.querySelectorAll<HTMLElement>("[data-i18n]")) {
            const value = translations[next][node.dataset.i18n || ''];
            if (value)
                node.innerHTML = value;
        }
        for (const button of document.querySelectorAll<HTMLButtonElement>("[data-product-screen]")) {
            const number = button.querySelector("span")?.textContent?.trim();
            const title = button.querySelector("h3")?.textContent?.trim();
            if (number && title) button.setAttribute("aria-label", `${number} · ${title}`);
        }
        for (const node of document.querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]")) {
            const value = translations[next][node.dataset.i18nPlaceholder || ''];
            if (value)
                node.placeholder = value;
        }
        for (const button of document.querySelectorAll<HTMLElement>("[data-lang]")) {
            button.classList.toggle("active", button.dataset.lang === next);
            button.setAttribute("aria-pressed", String(button.dataset.lang === next));
        }
        for (const select of document.querySelectorAll<HTMLSelectElement>('[data-language-select]')) select.value = next;
        window.dispatchEvent(new CustomEvent("luxmc-language-changed", { detail: { lang: next } }));
    }
    window.LuxI18n = {
        t: (key: any) => translations[language][key] || translations.pt[key] || key,
        setLanguage: applyLanguage,
        getLanguage: () => language,
    };
    function init() {
        for (const select of document.querySelectorAll<HTMLSelectElement>('[data-language-select]')) select.addEventListener('change', () => applyLanguage(select.value));
        applyLanguage(language);
        document
            .querySelectorAll<HTMLElement>("[data-lang]")
            .forEach((button: any) => button.addEventListener("click", () => applyLanguage(button.dataset.lang)));
    }
    if (document.readyState === "loading")
        document.addEventListener("DOMContentLoaded", init);
    else
        init();
