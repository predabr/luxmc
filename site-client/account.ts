function accountText(source: string): string {
    const lang = window.LuxI18n?.getLanguage() || (navigator.language.toLowerCase().startsWith('pt') ? 'pt' : navigator.language.toLowerCase().startsWith('es') ? 'es' : 'en');
    return lang === 'pt' ? source : accountTranslations[source]?.[lang === 'es' ? 1 : 0] || source;
}
function translateAccountPage() {
    const originals = new Map<string, string>();
    for (const [source, values] of Object.entries(accountTranslations)) { originals.set(source, source); for (const value of values) originals.set(value, source); }
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
        const node = walker.currentNode;
        if (node.parentElement?.closest('script,style,[data-i18n]')) continue;
        const text = node.textContent || '', source = originals.get(text.trim().replace(/\s+/g, ' '));
        if (source) node.textContent = text.replace(text.trim(), accountText(source));
    }
}
