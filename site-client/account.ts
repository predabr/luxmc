$("#microsoftLogin").addEventListener('click', async () => {
    const button = $("#microsoftLogin"), error = $("#microsoftError");
    button.disabled = true; error.hidden = true;
    try {
        const result = await api('start', {}, 'microsoft');
        const url = new URL(result.url);
        if (url.origin !== 'https://login.microsoftonline.com' || url.pathname !== '/consumers/oauth2/v2.0/authorize') throw new Error(accountText("Não foi possível abrir o acesso da Microsoft."));
        location.assign(url.href);
    } catch (cause: any) { error.textContent = cause.message; error.hidden = false; button.disabled = false; }
});
