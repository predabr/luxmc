async function api(action: any, body: any = {}, area: any = "account") {
    let response;
    try {
        response = await fetch(`/api/${area}/${action}`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify(body),
            credentials: "same-origin",
            signal: AbortSignal.timeout(15000),
        });
    }
    catch (err: any) {
        throw new Error(accountText("Falha na conexão com o servidor. Verifique se sua internet está ativa."));
    }
    let result;
    try {
        result = await response.json();
    }
    catch {
        throw Object.assign(new Error(accountText("O serviço de conta não respondeu como esperado. Tente novamente em instantes.")), { status: response.status });
    }
    if (!response.ok) {
        if (result.account) {
            current = result.account;
            fillPreferences();
        }
        const msg = response.status === 503 && area !== 'microsoft'
            ? accountText("O serviço de conta está temporariamente indisponível. Tente novamente em instantes.")
            : result.error ||
                `Erro no servidor (${response.status}). Tente novamente em instantes.`;
        throw Object.assign(new Error(msg), { status: response.status, suggestions: result.suggestions || [] });
    }
    return result;
}
