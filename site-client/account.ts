window.addEventListener('luxmc-session-ready', (event:Event) => {
    const detail=(event as CustomEvent).detail;
    if (current && detail?.user?.id === current.socialId) $("#accountAvatar").src = detail.avatar;
    else if (current && (!detail?.user || detail.user.id !== current.socialId)) {
        generation++; clearTimeout(poll); current=null;
        $("#dashboard").hidden=true; $("#authPanel").hidden=false;
        $("#generatedRecovery").value=''; $("#recoveryNotice").hidden=true;
        setMode('login');
    }
});
function friendRow(friend: any, search: any = false) {
    const row = document.createElement("div");
    row.className = "friend-row";
    const avatar = document.createElement("img");
    avatar.src =
        friend.avatarUrl ||
            `https://mc-heads.net/avatar/${encodeURIComponent(friend.username)}/64`;
    avatar.alt = "";
    const label = document.createElement("div");
    label.textContent = friend.username;
    if (friend.membership?.plan === 'plus' || friend.membership?.plan === 'pro') {
        const badge = document.createElement('small');
        badge.textContent = `Luxmc ${friend.membership.plan === 'pro' ? 'Pro' : 'Plus'}`;
        badge.style.color = 'rgb(var(--brand-400))';
        label.append(badge);
    }
    const status = document.createElement("small");
    status.textContent = search
        ? `#${friend.id.slice(0, 8)}`
        : friend.status === "pending"
            ? friend.incoming
                ? accountText("Convite recebido")
                : accountText("Convite enviado")
            : friend.status === "in_game"
                ? `Jogando ${friend.activity || "Minecraft"}`
                : friend.status === "online"
                    ? "Online"
                    : "Offline";
    label.append(status);
    row.append(avatar, label);
    const action = (name: any, text: any) => {
        const button = document.createElement("button");
        button.type = "button";
        button.textContent = text;
        button.addEventListener("click", async () => {
            button.disabled = true;
            try {
                await api(name, { targetId: friend.id }, "social");
                message(name === "invite" ? accountText("Convite enviado.") : accountText("Lista atualizada."));
                clearTimeout(poll);
                await refreshFriends(generation);
            }
            catch (error: any) {
                message(error.message, true);
            }
            finally {
                button.disabled = false;
            }
        });
        row.append(button);
    };
    if (search)
        action("invite", accountText("Adicionar"));
    else {
        if (friend.incoming && friend.status === "pending")
            action("accept", accountText("Aceitar"));
        action("remove", friend.status === "pending" ? accountText("Recusar / cancelar") : accountText("Remover"));
    }
    return row;
}
async function refreshFriends(run: any) {
    if (!current || run !== generation)
        return;
    try {
        const result = await api("sync", { readOnly: true }, "social");
        if (run !== generation)
            return;
        if (result.me.avatarUrl)
            $("#accountAvatar").src = result.me.avatarUrl;
        $("#friendsList").replaceChildren(...result.friends.map((friend: any) => friendRow(friend)));
        if (!result.friends.length) {
            const empty = document.createElement("p");
            empty.className = "empty-friends";
            empty.textContent =
                accountText("Sua próxima dupla está por aí. Busque um nickname para enviar um convite.");
            $("#friendsList").append(empty);
        }
    }
    catch (error: any) {
        if (run === generation)
            message(error.message, true);
    }
    if (run === generation && !document.hidden)
        poll = setTimeout(() => void refreshFriends(run), 25000);
}
